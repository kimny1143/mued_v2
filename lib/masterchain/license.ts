//
// masterchain ($69) license keyfile — Ed25519 issuance + verification.
//
// ★ THIS IS THE LICENSE SIGNATURE. It is NOT the FastSpring webhook HMAC.
//   Two different signatures live in this feature and they are easy to confuse:
//     - lib/masterchain/fastspring-signature.ts  = HMAC-SHA256, SYMMETRIC, shared secret with
//       FastSpring. Answers "did FastSpring send this webhook?". Secret: FASTSPRING_WEBHOOK_SECRET.
//     - this file                                = Ed25519, ASYMMETRIC. Answers "did WE issue this
//       license?". Private key: MASTERCHAIN_LICENSE_PRIVATE_KEY (signing, server-side only).
//       The matching PUBLIC key is compiled into the plugin binary (dsp), which verifies OFFLINE.
//   Do not describe the license as "HMAC" anywhere. A reader who conflates them will reach for the
//   wrong secret and get a keyfile no plugin will accept.
//
// ## Who issues, and why that changed
//
// docs/paid-line/c-plus-fastspring-reflux-webhook-design.md:90 says the key is generated by
// FastSpring's built-in generator and we merely record it. ★That is SUPERSEDED (2026-07-25, product):
// FastSpring does not hold our private key, so a FastSpring-generated string can never carry an
// Ed25519 signature that the plugin's baked-in public key will verify. The issuer must be us.
//
// docs/paid-line/c7-verify-license-branch-design.md:116 says the private key is held OFFLINE. ★That
// is RELAXED for the same reason: signing inside the order webhook requires the key to be readable by
// the server. kimny decision (2026-07-26): the private key lives in the Vercel environment.
// ★Consequence, recorded deliberately: verification is offline and there is no revocation (Q2a,
// DRM-free), so a leaked private key cannot be recalled — every already-shipped binary keeps trusting
// it. Recovery is "re-issue to every known buyer, then drop the old key in a new plugin build", which
// is only possible because masterchain_purchases keeps the buyer list. That ledger is not a
// convenience; it is the sole recovery path.
//
// ## Format (v1) — frozen; dsp verifies the same bytes
//
//   -----BEGIN MUEDSP LICENSE-----
//   <base64url(payload JSON)>.<base64url(ed25519 signature over the payload base64url bytes)>
//   -----END MUEDSP LICENSE-----
//
// The signature covers the ENCODED payload segment, not the raw JSON — so both sides sign/verify the
// exact same bytes and no JSON canonicalisation question arises (key order, whitespace, unicode
// escaping would otherwise all have to match across a TS issuer and a C++ verifier).
import { sign, verify, createPrivateKey, createPublicKey, type KeyObject } from "node:crypto";

export const LICENSE_VERSION = 1;
const BEGIN = "-----BEGIN MUEDSP LICENSE-----";
const END = "-----END MUEDSP LICENSE-----";

export interface LicensePayload {
  /** Buyer-facing name shown by the plugin. May be empty when FastSpring gives us no name. */
  name: string;
  /** Buyer email — the identity the license is bound to (lowercased by the caller). */
  email: string;
  /** Product this unlocks. Constant today; present so a second paid product does not need v2. */
  product: string;
  /** FastSpring order id — ties a keyfile back to exactly one purchase (support + re-issue). */
  orderId: string;
  /** ISO8601 issue time. Also what makes re-signing produce a DIFFERENT keyfile — see issueLicense. */
  issuedAt: string;
  /** Format version, so the plugin can reject or migrate old shapes. */
  v: number;
}

const b64url = (b: Buffer): string => b.toString("base64url");

/**
 * Read the signing key from the environment. Read at CALL time, never at module init — the same
 * reason fastspring-signature.ts:17 does it: a module-level read freezes the build-time value and
 * makes "I set the secret" silently ineffective.
 *
 * Returns null when unset. Callers MUST treat null as "cannot issue" — ★never as "issue unsigned".
 * (lib/plugins/unsubscribe-token.ts deliberately stays self-consistent with an empty key because it
 * only needs to match itself. That trick is CORRECT there and CATASTROPHIC here: an empty-key
 * signature is forgeable by anyone who reads this repository.)
 */
function privateKey(): KeyObject | null {
  const pem = process.env.MASTERCHAIN_LICENSE_PRIVATE_KEY;
  if (!pem) return null;
  try {
    return createPrivateKey(pem.includes("\\n") ? pem.replace(/\\n/g, "\n") : pem);
  } catch {
    // Do NOT log the value or the underlying error: a malformed-key error message can echo the input.
    return null;
  }
}

/** True when a signing key is present and usable — the "is this wired?" probe for callers/CI. */
export function isLicenseIssuingConfigured(): boolean {
  return privateKey() !== null;
}

/**
 * Issue a signed keyfile. Returns null when no signing key is configured (fail-CLOSED).
 *
 * ★NOT IDEMPOTENT BY ITSELF: `issuedAt` differs per call, so calling this twice for one order yields
 * two different (both valid) keyfiles. The caller is responsible for issuing once per order and
 * persisting the result — see handleFastspringOrderCompleted, which reads the stored keyfile back
 * before issuing. FastSpring retries webhooks; without that check one retry mails a second, different
 * key to the same buyer.
 */
export function issueLicense(
  input: Omit<LicensePayload, "issuedAt" | "v"> & { issuedAt?: string },
): string | null {
  const key = privateKey();
  if (!key) return null;

  const payload: LicensePayload = {
    name: input.name,
    email: input.email,
    product: input.product,
    orderId: input.orderId,
    issuedAt: input.issuedAt ?? new Date().toISOString(),
    v: LICENSE_VERSION,
  };

  const encoded = b64url(Buffer.from(JSON.stringify(payload), "utf8"));
  const signature = b64url(sign(null, Buffer.from(encoded, "utf8"), key));
  return `${BEGIN}\n${encoded}.${signature}\n${END}`;
}

/**
 * Verify a keyfile and return its payload, or null if anything is wrong. Pure — no env, no I/O; the
 * public key is passed in so tests can use a throwaway pair and CI can check the REAL pair.
 *
 * This exists next to the issuer on purpose: it lets a golden vector be pinned in our own tests, so
 * the format contract with dsp's C++ verifier is executable on this side rather than described.
 */
export function verifyLicense(keyfile: string, publicKeyPem: string): LicensePayload | null {
  try {
    const body = keyfile
      .replace(BEGIN, "")
      .replace(END, "")
      .trim();
    const dot = body.indexOf(".");
    if (dot <= 0 || dot === body.length - 1) return null;

    const encoded = body.slice(0, dot);
    const signature = body.slice(dot + 1);
    // Reject anything that is not clean base64url before touching crypto — Buffer.from is lenient
    // and would silently accept garbage, making a malformed keyfile look like a signature mismatch.
    if (!/^[A-Za-z0-9_-]+$/.test(encoded) || !/^[A-Za-z0-9_-]+$/.test(signature)) return null;

    const ok = verify(
      null,
      Buffer.from(encoded, "utf8"),
      createPublicKey(publicKeyPem),
      Buffer.from(signature, "base64url"),
    );
    if (!ok) return null;

    const parsed = JSON.parse(Buffer.from(encoded, "base64url").toString("utf8")) as LicensePayload;
    if (typeof parsed?.email !== "string" || typeof parsed?.orderId !== "string") return null;
    return parsed;
  } catch {
    return null;
  }
}
